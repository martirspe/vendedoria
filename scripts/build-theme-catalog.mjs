import { readFile, writeFile } from 'node:fs/promises';
import themes from '../packages/themes/catalog.js';
// Deterministic ESM facade of the canonical dependency-free catalog for frontend tree shaking.
let source = await readFile('packages/themes/catalog.js', 'utf8');
source = source.replace("'use strict';", "// Generated by scripts/build-theme-catalog.mjs; edit catalog.js and catalog.json.\nimport data from './catalog.json' with { type: 'json' };");
source = source.replace("require('./catalog.json')", 'data');
source = source.replace(/^exports\.(\w+) = \1;$/gm, 'export { $1 };');
await writeFile('packages/themes/catalog.mjs', source);
// The regular buyer entry only needs route identities; release/preset data loads in the demo chunk.
await writeFile('packages/themes/demo-index.mjs', '// Generated by scripts/build-theme-catalog.mjs.\nexport const THEME_DEMO_INDEX = Object.freeze(' + JSON.stringify(themes.latestThemes().map(theme => ({ slug: theme.slug, displayName: theme.displayName }))) + ');\n');
